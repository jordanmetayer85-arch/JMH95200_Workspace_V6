const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("jmhDesktop", {
  isElectron: true,
  atelierProtocol:2,
  atelierLaunch:value=>ipcRenderer.invoke('atelier:launch',value),
  atelierStop:()=>ipcRenderer.invoke('atelier:stop'),
  atelierCommand:(operation,value)=>ipcRenderer.invoke('atelier:'+operation,value),
  copyText:text=>ipcRenderer.invoke("clipboard:write",text),
  startDictation:()=>ipcRenderer.invoke('dictation:start'),
  windowsToolsProtocol:1,
  windowsStatus:()=>ipcRenderer.invoke("windows:status"),
  windowsVolume:value=>ipcRenderer.invoke("windows:volume",value),
  windowsSettings:key=>ipcRenderer.invoke("windows:settings",key),
  localFiles:(folder,offset)=>ipcRenderer.invoke("windows:list",folder,offset),
  openLocalFile:file=>ipcRenderer.invoke("windows:open",file),
  localLoginStatus:()=>ipcRenderer.invoke('credentials:status'),
  fillLocalLogin:username=>ipcRenderer.invoke('credentials:fill',username),
  saveLocalLogin:value=>ipcRenderer.invoke('credentials:save',value),
  clearLocalLogin:username=>ipcRenderer.invoke('credentials:clear',username),
  markLocalLoginUsed:username=>ipcRenderer.invoke('credentials:used',username),
  openStorageFile:relative=>ipcRenderer.invoke('storage:open-file',relative),
  getLocalTelemetry:()=>ipcRenderer.invoke('telemetry:get'),
  exportLocalDiagnostic:()=>ipcRenderer.invoke('telemetry:export'),
  getLocalDiagnostic:()=>ipcRenderer.invoke('telemetry:diagnostic'),
  vpnProxy:operation=>ipcRenderer.invoke('vpn:proxy',operation),
  openVpnMaps:()=>ipcRenderer.invoke('vpn:maps'),
  getConnectionConfig: () => ipcRenderer.invoke("connection:get"),
  connectionProtocol: 3,
  testVpnConnection: profile => ipcRenderer.invoke("connection:test-vpn", profile),
  testServerConnection: serverUrl => ipcRenderer.invoke("connection:test", serverUrl),
  getDesktopCapabilities: () => ipcRenderer.invoke("desktop:capabilities"),
  saveConnectionConfig: config => ipcRenderer.invoke("connection:save", config),
  openConnectionSettings: () => ipcRenderer.invoke("connection:open-settings"),
  updaterProtocol: 1,
  checkForUpdate: () => ipcRenderer.invoke("update:check"),
  installUpdate: () => ipcRenderer.invoke("update:download-and-run"),
  getAppBuild: () => ipcRenderer.invoke("app:build"),
  getAppVersion: () => ipcRenderer.invoke("app:version"),
  selectCinemaFiles: () => ipcRenderer.invoke("cinema:select-files"),
  selectCinemaFolder: () => ipcRenderer.invoke("cinema:select-folder"),
  selectMusicFiles: () => ipcRenderer.invoke("music:select-files"),
  selectMusicFolder: () => ipcRenderer.invoke("music:select-folder"),
  openMediaFile: (kind, id) => ipcRenderer.invoke("media:open-file", { kind, id })
});
